//! Project canonical material kernels with a pinned compiler, never by
//! maintaining a separate handwritten Metal interpretation.
use naga::back::msl;
use sha2::{Digest, Sha256};
use std::{error::Error, fs, path::Path};

fn digest(source: &str) -> String {
    format!(
        "sha256:{}",
        Sha256::digest(source.as_bytes())
            .iter()
            .map(|byte| format!("{byte:02x}"))
            .collect::<String>()
    )
}

fn output(path: &Path, source: &str, check: bool) -> Result<(), Box<dyn Error>> {
    if check {
        if fs::read_to_string(path)? != source {
            return Err(format!("stale material projection: {}", path.display()).into());
        }
    } else {
        fs::write(path, source)?;
    }
    Ok(())
}

fn main() -> Result<(), Box<dyn Error>> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let check = std::env::args().any(|arg| arg == "--check");
    let mut pins = String::from(
        "// Generated by generate-material-metal (Naga 30.0.1). Do not edit.\nimport Foundation\n\npublic enum WorldbendMaterialKernels {\n",
    );
    for (file, family, prefix, name, header) in [
        ("foil", "Foil", "worldbend_foil", "foil", "foil"),
        (
            "mesh_gradient",
            "MeshGradient",
            "worldbend_mesh_gradient_v2",
            "meshGradient",
            "mesh_gradient",
        ),
        (
            "mesh_gradient.v1",
            "MeshGradientV1",
            "worldbend_mesh_gradient",
            "meshGradientV1",
            "mesh_gradient",
        ),
    ] {
        let wgsl = fs::read_to_string(root.join(format!("crates/worldbend-core/src/{file}.wgsl")))?;
        let mut module = naga::front::wgsl::parse_str(&wgsl)?;
        for (_, function) in module.functions.iter_mut() {
            if let Some(name) = &mut function.name {
                *name = format!("{prefix}_{name}");
            }
        }
        for entry in &mut module.entry_points {
            entry.name = format!("{prefix}_{}", entry.name);
        }
        let info = naga::valid::Validator::new(
            naga::valid::ValidationFlags::all(),
            naga::valid::Capabilities::all(),
        )
        .validate(&module)?;
        let mut options = msl::Options {
            lang_version: (2, 4),
            fake_missing_bindings: false,
            ..Default::default()
        };
        for entry in &module.entry_points {
            let mut resources = msl::EntryPointResources::default();
            resources.resources.insert(
                naga::ResourceBinding {
                    group: 0,
                    binding: 0,
                },
                msl::BindTarget {
                    buffer: Some(0),
                    ..Default::default()
                },
            );
            options
                .per_entry_point_map
                .insert(entry.name.clone(), resources);
        }
        let pipeline = msl::PipelineOptions {
            vertex_pulling_transform: false,
            ..Default::default()
        };
        let (metal, translation) = msl::write_string(&module, &info, &options, &pipeline)?;
        let names: Vec<_> = translation
            .entry_point_names
            .into_iter()
            .collect::<Result<_, _>>()?;
        let expected = [format!("{prefix}_vs_main"), format!("{prefix}_fs_main")];
        if names != expected {
            return Err(format!("unexpected material entry points: {names:?}").into());
        }
        let source = format!(
            "// Generated from {header}.wgsl by Naga 30.0.1. Do not edit.\n// Canonical source: {}\n{metal}",
            digest(&wgsl)
        );
        output(
            &root.join(format!("crates/worldbend-core/src/{file}.metal")),
            &source,
            check,
        )?;
        output(&root.join(format!("packages/swiftui/Sources/WorldbendAppearance/Shaders/Worldbend{family}.generated.metal")), &source, check)?;
        pins.push_str(&format!("    public static let {name}SourceSHA256 = \"{}\"\n    public static let {name}CanonicalSHA256 = \"{}\"\n    public static let {name}Vertex = \"{}\"\n    public static let {name}Fragment = \"{}\"\n", digest(&source), digest(&wgsl), expected[0], expected[1]));
    }
    pins.push_str("}\n");
    output(
        &root.join("packages/swiftui/Sources/WorldbendAppearance/MaterialKernels.generated.swift"),
        &pins,
        check,
    )?;
    Ok(())
}
