// The canonical core owns mesh-gradient pixels. Keep the native Shader's literal
// source and the receiving binding's immutable resource identity in sync.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = await readFile(path.join(root, 'crates/worldbend-core/src/mesh_gradient.wgsl'), 'utf8');
const oldSource = await readFile(path.join(root, 'crates/worldbend-core/src/mesh_gradient.v1.wgsl'), 'utf8');
const oldHash = 'sha256:' + createHash('sha256').update(oldSource).digest('hex');
const oldNative = await readFile(path.join(root, 'packages/figma/shaders/mesh-gradient/legacy-v1.ts'), 'utf8');
const oldNativeHash = 'sha256:' + createHash('sha256').update(oldNative).digest('hex');
const hash = 'sha256:' + createHash('sha256').update(source).digest('hex');
const nativePath = path.join(root, 'packages/figma/shaders/mesh-gradient/main.ts');
const native = await readFile(nativePath, 'utf8');
const nextNative = native.replace(/var wgsl = `[\s\S]*?`/, () => 'var wgsl = `' + source + '`');
const generated = '// Generated by scripts/generate-mesh-gradient-kernel.mjs. Do not edit.\n' +
  'export const MESH_GRADIENT_KERNEL_ID = "worldbend.mesh-gradient.rgba@0.2";\n' +
  'export const MESH_GRADIENT_KERNEL_SHA256 = ' + JSON.stringify(hash) + ';\n' +
  'export const MESH_GRADIENT_KERNEL_RESOURCES = ' + JSON.stringify([
    {id:'worldbend.mesh-gradient.rgba@0.2',sha256:hash,source},
    {id:'worldbend.mesh-gradient.rgba@0.1',sha256:oldHash,source:oldSource},
  ]) + ' as const;\n';
const nativeHash = 'sha256:' + createHash('sha256').update(nextNative).digest('hex');
const nativeIdentity = '// Generated by scripts/generate-mesh-gradient-kernel.mjs. Do not edit.\n' +
  'export const MESH_GRADIENT_NATIVE_PROFILE = "worldbend.mesh-gradient.rgba@0.2";\n' +
  'export const MESH_GRADIENT_NATIVE_SOURCE_SHA256 = ' + JSON.stringify(nativeHash) + ';\n' +
  'export const MESH_GRADIENT_NATIVE_KERNEL_SHA256 = ' + JSON.stringify(hash) + ';\n' +
  'export const MESH_GRADIENT_V1_NATIVE_PROFILE = "worldbend.mesh-gradient.rgba@0.1";\n' +
  'export const MESH_GRADIENT_V1_NATIVE_SOURCE_SHA256 = ' + JSON.stringify(oldNativeHash) + ';\n';
await mkdir(path.dirname(path.join(root, 'packages/web/src/generated/mesh-gradient-kernel.ts')), { recursive: true });
const outputs = [
  [path.join(root, 'packages/figma/src/mesh-gradient-resource.generated.ts'), nativeIdentity],
  [nativePath, nextNative],
  [path.join(root, 'packages/web/src/generated/mesh-gradient-kernel.ts'), generated],
];
for (const [file, value] of outputs) {
  if (process.argv.includes('--check')) {
    if (await readFile(file, 'utf8') !== value) throw new Error('Mesh-gradient kernel projection is stale: ' + path.relative(root, file));
  } else await writeFile(file, value);
}
