import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "vite";

const outputFile = new URL("../crates/worldbend-mcp/src/figma-runtime.js", import.meta.url);
const bundle = await build({ configFile: false, logLevel: "silent", build: {
  write: false, target: "es2020", minify: "esbuild",
  lib: { entry: fileURLToPath(new URL("../packages/figma/src/agent-handoff.ts", import.meta.url)),
    name: "WorldbendFigmaHandoff", formats: ["iife"] },
} });
const output = Array.isArray(bundle) ? bundle[0].output : bundle.output;
const code = output.find(entry => entry.type === "chunk")?.code;
if (!code || Buffer.byteLength(code) > 32768) throw new Error("Figma handoff runtime exceeds 32 KiB");
const generated = "// Generated by scripts/build-figma-handoff-runtime.mjs from the shared Figma publisher.\n" + code;
if (process.argv.includes("--check")) {
  if (await readFile(outputFile, "utf8") !== generated) throw new Error("Figma handoff runtime is stale; regenerate it before building the Agent");
} else await writeFile(outputFile, generated);
