// The canonical core owns Foil's pixels. Keep the native Shader's literal
// source and the receiving binding's immutable resource identity in sync.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = await readFile(path.join(root, 'crates/worldbend-core/src/foil.wgsl'), 'utf8');
const hash = 'sha256:' + createHash('sha256').update(source).digest('hex');
const nativePath = path.join(root, 'packages/figma/shaders/foil/main.ts');
const native = await readFile(nativePath, 'utf8');
const nextNative = native.replace(/var wgsl = `[\s\S]*?`/, () => 'var wgsl = `' + source + '`');
const generated = '// Generated by scripts/generate-foil-kernel.mjs. Do not edit.\n' +
  'export const FOIL_KERNEL_ID = "worldbend.foil.rgba@0.1";\n' +
  'export const FOIL_KERNEL_SHA256 = ' + JSON.stringify(hash) + ';\n';
const nativeHash = 'sha256:' + createHash('sha256').update(nextNative).digest('hex');
const nativeIdentity = '// Generated by scripts/generate-foil-kernel.mjs. Do not edit.\n' +
  'export const FOIL_NATIVE_PROFILE = "worldbend.foil.rgba@0.1";\n' +
  'export const FOIL_NATIVE_SOURCE_SHA256 = ' + JSON.stringify(nativeHash) + ';\n' +
  'export const FOIL_NATIVE_KERNEL_SHA256 = ' + JSON.stringify(hash) + ';\n';
const outputs = [[path.join(root, 'packages/figma/src/foil-resource.generated.ts'), nativeIdentity], [nativePath, nextNative], [path.join(root, 'packages/web/src/generated/foil-kernel.ts'), generated]];
for (const [file, value] of outputs) {
  if (process.argv.includes('--check')) {
    if (await readFile(file, 'utf8') !== value) throw new Error('Foil kernel projection is stale: ' + path.relative(root, file));
  } else await writeFile(file, value);
}
